"""Generate M4 JSON Schemas and TypeScript from Pydantic. No hand-maintained mirror."""

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from apps.api.motion_contracts.models import (  # noqa: E402
    MotionComposition,
    MotionRecipe,
    MotionScene,
)
from apps.api.motion_contracts.registry import RegistryIndex  # noqa: E402
from apps.api.motion_contracts.render import MotionSceneSpec  # noqa: E402
from apps.api.motion_contracts.requests import EngineRequest  # noqa: E402

OUTPUT = ROOT / "contracts" / "motion" / "generated"
MODELS = (
    MotionScene,
    MotionComposition,
    MotionRecipe,
    RegistryIndex,
    MotionSceneSpec,
    EngineRequest,
)


def ts_type(schema):
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[1]
    if "const" in schema:
        return json.dumps(schema["const"], ensure_ascii=False)
    if "enum" in schema:
        return " | ".join(json.dumps(v, ensure_ascii=False) for v in schema["enum"])
    for keyword, separator in (("anyOf", " | "), ("oneOf", " | "), ("allOf", " & ")):
        if keyword in schema:
            return "(" + separator.join(ts_type(v) for v in schema[keyword]) + ")"
    kind = schema.get("type")
    if kind in {"string", "boolean", "null"}:
        return kind
    if kind in {"integer", "number"}:
        return "number"
    if kind == "array":
        if "prefixItems" in schema:
            return "[" + ", ".join(ts_type(v) for v in schema["prefixItems"]) + "]"
        item = ts_type(schema["items"])
        size = schema.get("minItems")
        if size is not None and size == schema.get("maxItems") and size <= 8:
            return "[" + ", ".join(item for _ in range(size)) + "]"
        return "(" + item + ")[]"
    if kind == "object":
        if "patternProperties" in schema:
            patterns = schema["patternProperties"]
            if len(patterns) != 1 or schema.get("properties"):
                raise ValueError("Unsupported schema map; extend generator explicitly")
            return "Record<string, " + ts_type(next(iter(patterns.values()))) + ">"
        if isinstance(schema.get("additionalProperties"), dict):
            return "Record<string, " + ts_type(schema["additionalProperties"]) + ">"
        required = set(schema.get("required", []))
        fields = [
            json.dumps(key) + ("" if key in required else "?") + ": " + ts_type(value) + ";"
            for key, value in sorted(schema.get("properties", {}).items())
        ]
        return "{ " + " ".join(fields) + " }"
    raise ValueError(f"Unsupported JSON Schema type; refusing to emit any/unknown: {schema}")


def artifacts():
    definitions = {}
    result = {}
    for model in MODELS:
        schema = model.model_json_schema(mode="validation")
        schema["$schema"] = "https://json-schema.org/draft/2020-12/schema"
        schema["$comment"] = (
            "Generated from Pydantic. Graph/temporal/binding/hash semantics "
            "require Python validators."
        )
        result[f"{model.__name__}.schema.json"] = (
            json.dumps(schema, ensure_ascii=False, indent=2, sort_keys=True) + "\n"
        )
        for name, definition in schema.get("$defs", {}).items():
            if name in definitions and definitions[name] != definition:
                raise ValueError(f"Conflicting definition: {name}")
            definitions[name] = definition
        root = {k: v for k, v in schema.items() if k not in {"$defs", "$schema", "$comment"}}
        if model.__name__ in definitions and definitions[model.__name__] != root:
            raise ValueError("Root definition mismatch")
        definitions[model.__name__] = root
    result["motion-contracts.ts"] = (
        "// Generated by scripts/generate_motion_contracts.py. Do not edit.\n"
        "// Input types only; constraints and semantic checks run in Python.\n"
        + "\n".join(
            f"export type {name} = {ts_type(value)};" for name, value in sorted(definitions.items())
        )
        + "\n"
    )
    examples = [
        "// Generated compile-time fixture check. No rendering or assets.",
        'import type {MotionComposition} from "./motion-contracts";',
    ]
    for label in ("sports", "music", "geo"):
        value = json.loads(
            (OUTPUT.parent / "fixtures" / label / "composition.json").read_text(encoding="utf-8")
        )
        examples.append(
            "export const "
            + label
            + " = "
            + json.dumps(value, ensure_ascii=False, indent=2)
            + " satisfies MotionComposition;"
        )
    result["fixture-types.ts"] = "\n".join(examples) + "\n"
    return result


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="Fail when committed outputs diverge")
    args = parser.parse_args()
    expected = artifacts()
    if args.check:
        stale = [
            name
            for name, value in expected.items()
            if not (OUTPUT / name).is_file() or (OUTPUT / name).read_text(encoding="utf-8") != value
        ]
        actual = {p.name for p in OUTPUT.iterdir()} if OUTPUT.is_dir() else set()
        stale += sorted(actual - set(expected))
        if stale:
            raise SystemExit("Generated contracts differ: " + ", ".join(stale))
        print("Generated JSON Schema/TypeScript/fixtures match Pydantic")
    else:
        OUTPUT.mkdir(parents=True, exist_ok=True)
        for name, value in expected.items():
            (OUTPUT / name).write_text(value, encoding="utf-8", newline="\n")
        print(f"Generated {len(expected)} contract artifacts")


if __name__ == "__main__":
    main()
