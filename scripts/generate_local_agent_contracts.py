"""Generate the local Ollama result contracts from their Pydantic source."""

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from apps.api.creative.local_agents import SCHEMAS  # noqa: E402
from scripts.generate_motion_contracts import ts_type  # noqa: E402

OUTPUT = ROOT / "contracts" / "local-agents" / "generated"


def artifacts() -> dict[str, str]:
    definitions = {}
    outputs = {}
    for task, model in SCHEMAS.items():
        schema = model.model_json_schema(mode="validation")
        schema["$schema"] = "https://json-schema.org/draft/2020-12/schema"
        outputs[f"{task}.schema.json"] = json.dumps(
            schema, ensure_ascii=False, indent=2, sort_keys=True
        ) + "\n"
        for name, definition in schema.get("$defs", {}).items():
            if name in definitions and definitions[name] != definition:
                raise ValueError(f"Conflicting definition: {name}")
            definitions[name] = definition
        definitions[model.__name__] = {
            key: value for key, value in schema.items() if key not in {"$defs", "$schema"}
        }
    outputs["local-agent-contracts.ts"] = (
        "// Generated by scripts/generate_local_agent_contracts.py. Do not edit.\n"
        "// Pydantic checks semantic constraints after Ollama responds.\n"
        + "\n".join(
            f"export type {name} = {ts_type(value)};"
            for name, value in sorted(definitions.items())
        ) + "\n"
    )
    return outputs


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = artifacts()
    if args.check:
        stale = [name for name, value in expected.items() if not (OUTPUT / name).is_file()
                 or (OUTPUT / name).read_text(encoding="utf-8") != value]
        if stale:
            raise SystemExit("Stale local agent contracts: " + ", ".join(stale))
        print("Local agent JSON Schema and TypeScript match Pydantic")
        return
    OUTPUT.mkdir(parents=True, exist_ok=True)
    for name, value in expected.items():
        (OUTPUT / name).write_text(value, encoding="utf-8", newline="\n")
    print(f"Generated {len(expected)} local agent contracts")


if __name__ == "__main__":
    main()
